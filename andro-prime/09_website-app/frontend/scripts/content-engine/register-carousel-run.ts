/**
 * register-carousel-run — put the 30-day Instagram carousel run into the database.
 *
 * Plan step 1.1 of `06_marketing/content-machine/2026-08-14-content-machine-plan.md`, the half
 * that follows the `variant` migration (D1, Keith 2026-08-14).
 *
 * WHY IT EXISTS. Thirty carousel posts were created in Metricool on 2026-08-13 and begin
 * publishing on 2026-08-17. Until they are registered they are invisible to `/content-status`,
 * unchecked by `content-doctor`, absent from every count in the STATE docs, and unreachable by
 * `metricool-writeback`, which only asks about renditions it can see. Registered before the run
 * starts, it records itself as it publishes. Registered afterwards, the per-day publish
 * timestamps have to be reconstructed.
 *
 * WHAT IT IS NOT. It does not create anything in Metricool and it never edits a post. The
 * thirty posts already exist; this ADOPTS them, which is a different and much safer act. The
 * only writes are to `content_assets` and `content_renditions`.
 *
 * HOW A POST IS MATCHED TO A ROW, and why it is not by position. The run is generated by
 * `06_marketing/content/instagram/carousel-prototype/schedule.js`, which derives every day from
 * `covers.js` and parses the captions straight out of `captions.md` (the CA-035 artefact). This
 * script asks that same generator for the run, then matches each day to the Metricool post
 * occupying that day's SLOT, and then REFUSES the match unless the post's own text is the
 * approved caption for that topic byte for byte. Sorting two lists and zipping them would look
 * identical on a good day and attach the wrong post id on a bad one, and a wrong id is a
 * rendition that reports someone else's publication as its own.
 *
 * WHAT MAKES A BAD RUN RECOVERABLE: `--dry-run` prints every insert and update it would make and
 * performs none; every write is keyed by slug or by rendition id; nothing is ever deleted; and a
 * second run over an already-registered run reports "no change" rather than duplicating, because
 * the unique key is now `(asset_id, platform, format, variant)`.
 */
