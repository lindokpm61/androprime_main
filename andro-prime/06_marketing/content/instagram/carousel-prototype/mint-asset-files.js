/*
 * Mint one content-machine asset file per carousel topic. Generated, not hand-typed.
 *
 *   node mint-asset-files.js --check   report what differs, write nothing, exit 1 on any drift
 *   node mint-asset-files.js           write the ten files
 *
 * WHY THESE FILES EXIST. `content-doctor` invariant I1 requires a content_assets row to have an
 * assets/*.md file, and the ten carousel rows registered on 2026-08-14 had none. The two
 * exemptions I1 already carries do not fit: a batch draft can only cover assets that share one
 * canonical article (the X week's seven do; these ten have ten different articles), and the
 * substack exemption is scoped to verbatim republishes. So the file is genuinely owed.
 *
 * WHAT IS AND IS NOT IN THEM, and the line is deliberate.
 *
 * NOT the caption or the slide copy. That is approved copy (CA-034 for the slides, CA-035 for
 * the captions), and a second copy of approved copy is one that can be edited without going
 * back through Ewa — the same reason `schedule.js` parses captions.md rather than restating it.
 * The copy that shipped is recorded once, in `content_renditions.body`, which is the column that
 * means "what actually went out".
 *
 * WHAT IS in them: identity, the deck's SHAPE (eight slides by type and eyebrow, which is the
 * structural decision a human made and a diff of which is meaningful), the close set under test,
 * the kit close B names and why that constraint exists, and the approval trail. Everything here
 * is derived from covers.js, the deck files and closes.js, so the file cannot disagree with the
 * artefacts it describes: re-run this and the difference is the answer.
 */

const fs = require('fs');
const path = require('path');
const { TOPIC_ORDER, coverFor } = require('./covers');
const { KITS, closesFor } = require('./closes');

const ASSETS_DIR = path.join(__dirname, '..', '..', '..', 'content-machine', 'assets');
const MINT_DATE = '2026-08-14';
const SERIES = 'carousel-30-2026-08';

/* The rotation, identical to schedule.js: topic = day mod 10, close = day mod 3. Derived here
 * rather than imported because schedule.js emits a whole run and this needs the inverse (which
 * days belong to a topic), and re-deriving two lines is cheaper than a second export that could
 * drift. `schedule.js --check` is what proves the rotation itself. */
function appearancesFor(topicIndex, runDays = 30) {
  const out = [];
  for (let day = 1; day <= runDays; day++) {
    if ((day - 1) % TOPIC_ORDER.length === topicIndex) out.push({ day, close: 'ABC'[(day - 1) % 3] });
  }
  return out;
}

/** One line per slide: the structural decision, without the copy that carries it. */
function shapeOf(deck) {
  return deck.slides.map((s, i) => {
    const kind = s.type + (s.items ? ` (${s.items.length})` : '');
    return `${i + 1}. **${s.eyebrow || '(no eyebrow)'}** · ${kind}`;
  });
}

function fileFor(topicIndex) {
  const slug = TOPIC_ORDER[topicIndex];
  const cover = coverFor(slug);
  const deck = require(`./decks/${slug}.js`);
  const closes = closesFor(deck);
  const appearances = appearancesFor(topicIndex);
  const kit = KITS[deck.kit];

  const L = [];
  L.push('---');
  L.push(`slug: carousel-${slug}`);
  L.push(`title: ${cover.title}`);
  L.push('content_type: educational');
  L.push('funnel_stage: TOFU');
  L.push(`funnel_job: problem-aware Instagram carousel for "${slug}", 30-day close test`);
  L.push('awareness: problem-aware');
  L.push('channel: instagram');
  L.push(`canonical_asset: ${slug}`);
  L.push(`series: ${SERIES}`);
  L.push('renditions:');
  // Listed A, B, C rather than in day order: the frontmatter says which renditions EXIST, and
  // the three are read as a set. Their dates are state and live in the mirror below.
  for (const a of [...appearances].sort((x, y) => (x.close < y.close ? -1 : 1))) {
    L.push('  - platform: instagram');
    L.push('    format: carousel');
    L.push('    thumb: none');
    L.push(`    variant: ${a.close}`);
  }
  L.push('---');
  L.push('');
  L.push(`_Generated by \`content/instagram/carousel-prototype/mint-asset-files.js\`. Edit the deck, \`covers.js\` or \`closes.js\` and re-run; hand edits to the sections below are overwritten._`);
  L.push('');
  L.push('## What this is');
  L.push('');
  L.push(`One of ten topics on the 30-day Instagram carousel run (\`${SERIES}\`), ${appearances.map((a) => `day ${a.day} (close ${a.close})`).join(', ')}. Eight slides, seven shared and the eighth swapped: **the closing slide is the only thing that varies across the three, and that is the whole experiment.**`);
  L.push('');
  L.push(`Claims are inherited from the canonical article \`${slug}\`, which is published and Ewa-signed. Nothing on the deck is net-new.`);
  L.push('');
  L.push('## No single `cta`, on purpose');
  L.push('');
  L.push('The three variants ask for three different things, so the asset carries no `cta` field: the CTA is a property of the variant, not of the idea.');
  L.push('');
  L.push('| variant | close | asks for |');
  L.push('| --- | --- | --- |');
  L.push(`| A | ${closes.A.eyebrow} | the quiz |`);
  L.push(`| B | ${closes.B.eyebrow} | ${kit.name} (${kit.price}) |`);
  L.push(`| C | ${closes.C.eyebrow} | the canonical article |`);
  L.push('');
  L.push(`The mapping is fixed in \`closes.js\` and approved as **CA-031** (2026-08-11). **K2 of CA-034** (Keith, 2026-08-12) reframed close C as a *delayed kit offer* rather than a no-ask arm, so all three arms end at something we sell and the run tests one offer at three distances.`);
  L.push('');
  L.push(`Close B names **${kit.name}**, and which kit it may name is a compliance constraint rather than a preference: \`decks/${slug}.js\` carries the reason in its own header.`);
  L.push('');
  L.push('## Deck shape');
  L.push('');
  L.push('The structural decision, without the copy. Slide copy lives in `decks/' + slug + '.js` and was approved under **CA-034**; the caption and first comment live in `captions.md` under **CA-035**, and the copy that actually shipped is in `content_renditions.body`. None of it is restated here, because a second copy of approved copy is one that can be edited without going back through Ewa.');
  L.push('');
  for (const line of shapeOf(deck)) L.push(line);
  L.push(`8. **close** · one of A, B or C (see above)`);
  L.push('');
  L.push(`Cover: \`${cover.eyebrow}\`, headline "${cover.l1} / ${cover.l2}", set once in \`covers.js\` for both the inpainted newsprint and the type plate. The cover format alternates between video and type across the three appearances, which is a property of the appearance rather than of the topic.`);
  L.push('');
  L.push('## Approvals');
  L.push('');
  L.push('- **CA-031** (2026-08-11): the three closing slides.');
  L.push('- **CA-034** (2026-08-12): the per-post pre-flight across all 30 assembled posts, 7 of 7 ruled. Packet: `03_compliance/content-approval/signoff-packet-carousel-30-posts-2026-08-12.md`, board [`869ehd4wm`](https://app.clickup.com/t/869ehd4wm).');
  L.push('- **CA-035** (2026-08-12): the captions and first comments, Ewa and Keith.');
  L.push('');
  L.push(`Registered into the database on ${MINT_DATE} by \`scripts/content-engine/register-carousel-run.ts\`, which adopts the Metricool posts rather than creating them and refuses any day whose post does not carry the approved caption.`);
  L.push('');
  return { path: path.join(ASSETS_DIR, `${MINT_DATE}-carousel-${slug}.md`), text: L.join('\n') };
}

/* A file that already carries a generated state block keeps it: content-sync owns that region,
 * this script owns everything else, and regenerating must not delete the mirror. */
const BEGIN = '<!-- BEGIN GENERATED STATE.';
const END = '<!-- END GENERATED STATE -->';

function preserveStateBlock(next, existing) {
  if (!existing) return next;
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (start === -1 || end === -1) return next;
  const block = existing.slice(start, end + END.length);
  const fmEnd = next.indexOf('\n---\n', 4);
  if (fmEnd === -1) return next;
  const head = next.slice(0, fmEnd + 5);
  const rest = next.slice(fmEnd + 5);
  return `${head}\n${block}\n${rest}`;
}

const checkOnly = process.argv.includes('--check');
let changed = 0;

for (let i = 0; i < TOPIC_ORDER.length; i++) {
  const { path: p, text } = fileFor(i);
  const existing = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  const next = preserveStateBlock(text, existing);
  if (existing === next) { console.log(`  same   ${path.basename(p)}`); continue; }
  changed++;
  if (checkOnly) { console.log(`  DIFFERS ${path.basename(p)}`); continue; }
  fs.writeFileSync(p, next);
  console.log(`  ${existing ? 'update' : 'write '} ${path.basename(p)}`);
}

console.log(`\n${TOPIC_ORDER.length} topic(s), ${changed} ${checkOnly ? 'differing' : 'written'}.`);
if (checkOnly && changed) process.exitCode = 1;
